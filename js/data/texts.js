/** Builds the typeable text for a passage (Qur'an verses get skipped verse numbers). */
function passageText(item) {
  if (item.verses) {
    return item.verses.map((v, i) => `${v} {(${toArabicDigits(item.start + i)})}`).join(' ');
  }
  return item.text;
}
